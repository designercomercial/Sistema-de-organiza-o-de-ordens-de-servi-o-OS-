import { questionnaires } from "@/data/questionnaires"
import type { ChecklistItem, ServiceOrder, ServiceOrderStatus, Priority } from "@/types"

export function buildChecklist(questionnaireId: string, doneCount = 0): ChecklistItem[] {
  const questionnaire = questionnaires.find((item) => item.id === questionnaireId)
  if (!questionnaire) return []
  return questionnaire.questions.map((question, index) => ({
    id: question.id,
    title: question.title,
    type: question.type,
    required: question.required,
    options: question.options,
    done: index < doneCount,
  }))
}

